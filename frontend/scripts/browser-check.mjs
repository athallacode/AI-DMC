// Integration QA against a running backend and frontend. Synthetic data only.
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const playwright = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : require('playwright');
const base = process.env.QA_FRONTEND_URL || 'http://localhost:3000';
const backend = process.env.QA_BACKEND_URL || 'http://localhost:8000';
const username = process.env.QA_USERNAME || 'dosen1';
if (!process.env.QA_PASSWORD) throw new Error('Set QA_PASSWORD to the seed password for the QA backend.');
const output = path.resolve('../docs/screenshots');
await fs.mkdir(output, {recursive:true});
const browser = await playwright.chromium.launch({headless:true, channel:'chrome'});
const page = await browser.newPage({viewport:{width:1280,height:900}});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
async function noOverflow() {assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth),false,'No horizontal overflow');}
async function shot(name, fullPage = true) {await noOverflow(); await page.screenshot({path:path.join(output,name),fullPage});}
try {
  await page.goto(`${base}/login`);
  await page.getByRole('heading',{name:'Masuk',exact:true}).waitFor();
  await shot('login-desktop.png');
  await page.setViewportSize({width:375,height:812}); await shot('login-mobile.png');
  await page.getByLabel('Username',{exact:true}).fill(username);
  await page.getByLabel('Password',{exact:true}).fill(process.env.QA_PASSWORD);
  await page.getByRole('button',{name:'Masuk',exact:true}).click();
  await page.waitForURL('**/unggah');
  await page.getByRole('heading',{name:'Unggah',exact:true}).waitFor();
  await page.getByText('Mode demo', {exact:false}).waitFor();
  await shot('unggah-mobile.png');
  await page.setViewportSize({width:1280,height:900}); await shot('unggah-desktop.png');
  const fixtureDir = process.env.QA_FIXTURE_DIR;
  if (!fixtureDir) throw new Error('Set QA_FIXTURE_DIR containing high.pdf, low.pdf, low.docx, high.png, fail.png.');
  const names = ['high.pdf','low.pdf','low.docx','high.png','fail.png'];
  await page.locator('input[type=file][multiple]').setInputFiles(names.map(name => path.join(fixtureDir,name)));
  await page.getByRole('heading',{name:'Antrean unggah'}).waitFor();
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('.queue-row')).some(el => /Memproses dokumen|Mengunggah/.test(el.textContent || '')), {timeout:30000});
  await page.getByRole('button',{name:'Tutup',exact:true}).click();
  await page.locator('.desktop-nav').getByRole('link',{name:/Verifikasi/}).click();
  await page.getByRole('heading',{name:'Kotak Verifikasi',exact:true}).waitFor();
  await page.locator('.verification-card').first().waitFor();
  await page.getByText('AI kurang yakin, mohon dicek.',{exact:true}).first().waitFor();
  await page.locator('.preview').first().locator('iframe, img, .empty').waitFor();
  await page.waitForTimeout(700);
  await shot('verifikasi-desktop.png');
  const card = page.locator('.verification-card').filter({has:page.getByRole('heading',{name:'low.pdf',exact:true})});
  await card.getByRole('button',{name:'Setujui',exact:true}).click();
  await page.getByRole('button',{name:'Urungkan',exact:true}).click();
  await page.waitForTimeout(3300);
  assert.equal(await card.count(),1,'Undo keeps document pending');
  await card.getByRole('button',{name:'Setujui',exact:true}).click();
  await card.waitFor({state:'detached',timeout:10000});
  const remaining = page.locator('.verification-card').filter({has:page.getByRole('heading',{name:'low.docx',exact:true})}).first();
  await remaining.getByRole('button',{name:'Koreksi',exact:true}).click();
  const modal = page.getByRole('dialog',{name:'Koreksi dokumen',exact:true});
  await modal.waitFor();
  await modal.getByLabel('Judul',{exact:false}).fill('Dokumen hasil koreksi QA');
  await page.setViewportSize({width:375,height:812}); await page.waitForTimeout(300); await shot('koreksi-mobile.png', false);
  await modal.getByRole('button',{name:'Simpan dan setujui',exact:true}).click();
  await modal.waitFor({state:'detached'});
  await shot('verifikasi-mobile.png');
  await page.locator('.mobile-nav').getByRole('link',{name:'Arsip',exact:true}).click();
  await page.getByRole('heading',{name:'Arsip Saya',exact:true}).waitFor();
  await page.getByRole('button',{name:'Dokumen hasil koreksi QA',exact:true}).first().waitFor();
  await shot('arsip-mobile.png');
  await page.setViewportSize({width:1280,height:900}); await shot('arsip-desktop.png');
  await page.getByRole('button',{name:'PND',exact:true}).click();
  await page.getByRole('button',{name:'Dokumen hasil koreksi QA',exact:true}).first().waitFor();
  await page.getByRole('button',{name:'Semua',exact:true}).click();
  await page.locator('.filter-fields select').selectOption('gagal');
  await page.getByRole('button',{name:/fail.png/}).first().waitFor();
  const authToken = await page.evaluate(() => sessionStorage.getItem('ai-dmc-token'));
  const documents = await (await fetch(`${backend}/documents`, {headers:{Authorization:`Bearer ${authToken}`}})).json();
  assert(documents.some(doc => doc.nama_berkas === 'fail.png' && doc.status === 'gagal'));
  assert(documents.some(doc => doc.nama_berkas === 'low.pdf' && doc.status === 'terverifikasi'));
  assert(documents.some(doc => doc.nama_berkas === 'low.docx' && doc.judul === 'Dokumen hasil koreksi QA' && doc.status === 'terverifikasi'));
  assert.equal(errors.length,0,`Browser errors: ${errors.join('; ')}`);
  console.log(JSON.stringify({passed:true,screenshots:output,documentCount:documents.length,browserErrors:errors}));
} finally {await browser.close();}
